import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { pathToFileURL, fileURLToPath } from 'node:url';

const pkg = process.env.PI_PACKAGE_DIR ?? join(execFileSync('npm', ['root', '-g'], { encoding: 'utf8' }).trim(), '@earendil-works/pi-coding-agent');
const { ModelRuntime, ModelRegistry, discoverAndLoadExtensions, createAgentSession, SessionManager, SettingsManager } = await import(pathToFileURL(join(pkg, 'dist/index.js')));
const extensionPath = fileURLToPath(new URL('..', import.meta.url));
const credential = id => ({ type: 'oauth', accountId: id, refresh: `fake-refresh-${id}`, expires: Date.now() + 3600_000,
    access: 'header.' + Buffer.from(JSON.stringify({ 'https://api.openai.com/auth': { chatgpt_account_id: id } })).toString('base64url') + '.signature' });
const sse = () => {
    const item = { id: 'msg_fake', type: 'message', role: 'assistant', status: 'completed', content: [{ type: 'output_text', text: 'ok', annotations: [] }] };
    const events = [
        { type: 'response.created', response: { id: 'resp_fake', status: 'in_progress' } },
        { type: 'response.output_item.added', output_index: 0, item: { ...item, content: [] } },
        { type: 'response.output_text.delta', output_index: 0, item_id: item.id, content_index: 0, delta: 'ok' },
        { type: 'response.output_item.done', output_index: 0, item },
        { type: 'response.completed', response: { id: 'resp_fake', status: 'completed', output: [item], usage: { input_tokens: 5, output_tokens: 1, total_tokens: 6 } } },
    ];
    return new Response(events.map(e => `data: ${JSON.stringify(e)}\n\n`).join(''), { headers: { 'content-type': 'text/event-stream' } });
};

test('real Pi loader/runtime, native Codex SSE adapter, failover, continuation, reload and old virtual selection', async t => {
    const root = mkdtempSync(join(tmpdir(), 'codex-loader-test-')); t.after(() => rmSync(root, { recursive: true, force: true }));
    const previous = process.env.PI_CODING_AGENT_DIR; process.env.PI_CODING_AGENT_DIR = root;
    const fetchBefore = globalThis.fetch;
    globalThis.fetch = async () => { throw new Error('Live network is forbidden in this test'); };
    t.after(() => { globalThis.fetch = fetchBefore; if (previous === undefined) delete process.env.PI_CODING_AGENT_DIR; else process.env.PI_CODING_AGENT_DIR = previous; });
    writeFileSync(join(root, 'auth.json'), JSON.stringify({ 'codex-a': credential('a'), 'codex-b': credential('b'), other: { type: 'api_key', key: 'keep' } }));
    const originalSettings = '{"defaultProvider":"codex-multi","defaultModel":"auto"}';
    writeFileSync(join(root, 'settings.json'), originalSettings);
    const boot = async () => {
        const loaded = await discoverAndLoadExtensions([extensionPath], root, root);
        assert.deepEqual(loaded.errors, []);
        assert.equal(loaded.extensions.length, 1);
        const runtime = await ModelRuntime.create({ authPath: join(root, 'auth.json'), modelsPath: null, modelsStorePath: join(root, 'models-cache.json'), refreshOnCreate: false });
        for (const { provider } of loaded.runtime.pendingNativeProviderRegistrations) runtime.registerNativeProvider(provider);
        for (const { definition } of loaded.runtime.pendingVirtualModelRegistrations) runtime.registerVirtualModel(definition);
        await runtime.refresh({ allowNetwork: false });
        const registry = new ModelRegistry(runtime);
        loaded.runtime.getSettings = () => ({ defaultProvider: 'codex-multi', defaultModel: 'auto' });
        loaded.runtime.createContext = () => ({ modelRegistry: registry });
        // One actual sign-in method, including virtual providers auto-generated by Pi.
        const logins = runtime.getProviders().filter(p => p.auth.oauth?.login || p.auth.apiKey?.login).filter(p => p.id === 'openai-codex' || p.id.startsWith('codex-'));
        assert.deepEqual(logins.map(p => p.id), ['openai-codex']);
        return { runtime, loaded };
    };
    const { runtime } = await boot();
    const calls = [];
    let hooks = 0;
    const mockFetch = async (_url, opts) => {
        const id = new Headers(opts.headers).get('ChatGPT-Account-Id');
        calls.push(id);
        if (calls.length === 1) return new Response(JSON.stringify({ error: { type: 'usage_limit_reached', message: "You've hit your usage limit. Try again in ~3 min." } }), { status: 429 });
        return sse();
    };
    const options = { transport: 'sse', fetch: mockFetch, onResponse: () => { hooks++; } };
    const model = runtime.getModel('openai-codex', 'gpt-5.5');
    assert.ok(model);
    const result = await runtime.streamSimple(model, { messages: [{ role: 'user', content: 'test', timestamp: Date.now() }] }, options).result();
    assert.equal(result.stopReason, 'stop', result.errorMessage);
    assert.equal(result.content[0].text, 'ok');
    assert.equal(result.provider, 'openai-codex');
    assert.deepEqual(calls, ['a', 'b']);
    assert.equal(hooks, 2);
    const continued = await runtime.streamSimple(model, { messages: [result, { role: 'user', content: 'continue', timestamp: Date.now() }] }, options).result();
    assert.equal(continued.stopReason, 'stop', continued.errorMessage);
    assert.deepEqual(calls, ['a', 'b', 'b']);
    const reloaded = await boot();
    const virtual = reloaded.runtime.getModel('codex-multi', 'auto');
    const route = await reloaded.runtime.resolveModel(virtual, [result], { reason: 'continuation', thinkingLevel: 'medium' });
    assert.equal(route.model.provider, 'openai-codex');
    assert.equal(route.model.id, 'gpt-5.5');
    const resumed = await reloaded.runtime.streamSimple(route.model, { messages: [result] }, options).result();
    assert.equal(resumed.stopReason, 'stop', resumed.errorMessage);
    assert.equal(calls.at(-1), 'b');
    const legacyAccount = reloaded.runtime.getModel('codex-a', 'gpt-5.5');
    const legacyRoute = await reloaded.runtime.resolveModel(legacyAccount, [], { reason: 'user', thinkingLevel: 'medium' });
    assert.equal(legacyRoute.model.provider, 'openai-codex');
    const throttleCalls = [];
    const throttled = await reloaded.runtime.streamSimple(route.model, { messages: [] }, { transport: 'sse', maxRetries: 0,
        fetch: async (_url, opts) => { throttleCalls.push(new Headers(opts.headers).get('ChatGPT-Account-Id')); return new Response(JSON.stringify({ error: { code: 'rate_limit_exceeded', message: 'Too many requests. Slow down.' } }), { status: 429 }); } }).result();
    assert.equal(throttled.stopReason, 'error'); assert.match(throttled.errorMessage, /rate_limit_exceeded/);
    assert.deepEqual(throttleCalls, ['b']); // native adapter's generic JSON-429 wording must not cause false quota failover
    assert.equal(JSON.parse(readFileSync(join(root, 'codex-accounts.json'))).accounts['codex-b']?.blockedUntil, undefined);
    let transientAttempts = 0;
    const retried = await reloaded.runtime.streamSimple(route.model, { messages: [] }, { transport: 'sse', maxRetries: 1,
        fetch: async () => { transientAttempts++; if (transientAttempts === 1) throw new Error('Connection reset'); return sse(); } }).result();
    assert.equal(retried.stopReason, 'stop', retried.errorMessage); assert.equal(transientAttempts, 2);
    assert.equal(readFileSync(join(root, 'settings.json'), 'utf8'), originalSettings);
    assert.equal(JSON.parse(readFileSync(join(root, 'auth.json'))).other.key, 'keep');
});

test('real AgentSession recovers legacy physical/virtual selections on resume, reload, model selection and after native login', async t => {
    const root = mkdtempSync(join(tmpdir(), 'codex-restored-session-'));
    const previous = process.env.PI_CODING_AGENT_DIR, originalFetch = globalThis.fetch;
    process.env.PI_CODING_AGENT_DIR = root;
    globalThis.fetch = async () => { throw new Error('Live network is forbidden'); };
    t.after(() => { rmSync(root, { recursive: true, force: true }); globalThis.fetch = originalFetch;
        if (previous === undefined) delete process.env.PI_CODING_AGENT_DIR; else process.env.PI_CODING_AGENT_DIR = previous; });
    const legacyProvider = 'codex-11111111-2222-4333-8444-555555555555';
    const accountId = legacyProvider.slice('codex-'.length);
    writeFileSync(join(root, 'auth.json'), JSON.stringify({ 'openai-codex': credential(accountId) }));
    writeFileSync(join(root, 'codex-accounts.json'), JSON.stringify({ version: 2, migrated: true, default: legacyProvider,
        addedOrder: [legacyProvider], legacyAliases: [legacyProvider], legacyAuto: true, accounts: {} }));
    const settingsText = '{"defaultProvider":"codex-multi","defaultModel":"auto"}';
    writeFileSync(join(root, 'settings.json'), settingsText);
    let extensions;
    const loader = {
        getExtensions: () => extensions,
        getSkills: () => ({ skills: [], diagnostics: [] }), getPrompts: () => ({ prompts: [], diagnostics: [] }),
        getThemes: () => ({ themes: [], diagnostics: [] }), getAgentsFiles: () => ({ agentsFiles: [] }),
        getSystemPrompt: () => 'Test', getSystemPromptSource: () => undefined, getAppendSystemPrompt: () => [], getAppendSystemPromptSources: () => [],
        extendResources() {}, reload: async () => {
            extensions = await discoverAndLoadExtensions([extensionPath], root, root);
            assert.deepEqual(extensions.errors, []);
        },
    };
    await loader.reload();
    const runtime = await ModelRuntime.create({ authPath: join(root, 'auth.json'), modelsPath: null, modelsStorePath: join(root, 'cache.json'), refreshOnCreate: false });
    const legacyModel = { ...runtime.getModel('openai-codex', 'gpt-5.5'), provider: legacyProvider, id: 'gpt-6.1-sol', name: 'Legacy dynamically discovered model' };
    assert.equal(legacyModel.api, 'openai-codex-responses');
    assert.ok(extensions.extensions[0].handlers.has('session_start'));
    const manager = SessionManager.inMemory(root);
    manager.appendModelChange(legacyProvider, legacyModel.id);
    const { session } = await createAgentSession({ cwd: root, agentDir: root, modelRuntime: runtime, model: legacyModel,
        resourceLoader: loader, sessionManager: manager, settingsManager: SettingsManager.inMemory({ compaction: { enabled: false }, retry: { enabled: false }, cacheWarming: 'off' }),
        tools: [], sessionStartEvent: { type: 'session_start', reason: 'resume' } });
    t.after(() => session.dispose());
    const errors = [];
    await session.bindExtensions({ mode: 'print', onError: error => errors.push(error) });
    assert.deepEqual(errors, []);
    assert.equal(session.model.provider, 'openai-codex');
    assert.equal(session.model.id, 'gpt-6.1-sol');
    const calls = [];
    session.agent.streamFunction = (m, c, o) => runtime.streamSimple(m, c, { ...o, transport: 'sse', fetch: async (_url, opts) => {
        calls.push(new Headers(opts.headers).get('ChatGPT-Account-Id')); return sse(); } });
    await session.prompt('test restored session', { source: 'rpc' });
    assert.equal(session.messages.at(-1).stopReason, 'stop', session.messages.at(-1).errorMessage);
    assert.equal(session.messages.at(-1).provider, 'openai-codex');
    assert.equal(session.messages.at(-1).model, 'gpt-6.1-sol');
    assert.deepEqual(calls, [accountId]);
    assert.deepEqual(errors, []);
    session.agent.state.model = legacyModel; // stale selection surviving an in-process extension upgrade
    await session.reload();
    assert.equal(session.model.provider, 'openai-codex'); assert.equal(session.model.id, 'gpt-6.1-sol');
    await session.prompt('test after reload', { source: 'rpc' });
    assert.equal(session.messages.at(-1).stopReason, 'stop');
    const uncatalogued = { ...legacyModel, id: 'gpt-legacy-uncatalogued' };
    assert.equal(runtime.getModel('openai-codex', uncatalogued.id), undefined);
    await session.setModel(uncatalogued); // physical object selected by an SDK client, not a catalog alias
    assert.equal(session.model.provider, 'openai-codex'); assert.equal(session.model.id, uncatalogued.id);
    assert.equal(session.model.api, 'openai-codex-responses');
    await session.prompt('test uncatalogued legacy selection', { source: 'rpc' });
    assert.equal(session.messages.at(-1).stopReason, 'stop', session.messages.at(-1).errorMessage);
    assert.equal(session.messages.at(-1).model, uncatalogued.id);
    // Native /login can happen after startup, which previously left the stale selection untouched.
    await runtime.logout('openai-codex');
    session.agent.state.model = legacyModel;
    await session.bindExtensions({ mode: 'print', onError: error => errors.push(error) });
    assert.equal(session.model.provider, legacyProvider); // no credential: do not claim recovery succeeded
    writeFileSync(join(root, 'auth.json'), JSON.stringify({ 'openai-codex': credential(accountId) }));
    await runtime.refresh({ allowNetwork: false });
    await session.prompt('test after native sign-in', { source: 'rpc' });
    assert.equal(session.model.provider, 'openai-codex'); assert.equal(session.model.id, 'gpt-6.1-sol');
    assert.equal(session.messages.at(-1).stopReason, 'stop');
    assert.deepEqual(errors, []);
    assert.equal(readFileSync(join(root, 'settings.json'), 'utf8'), settingsText);
    assert.ok(manager.getBranch().some(e => e.type === 'model_change' && e.provider === 'openai-codex' && e.modelId === 'gpt-6.1-sol'));
});
